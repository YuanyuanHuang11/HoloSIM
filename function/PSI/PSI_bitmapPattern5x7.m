function pat = PSI_bitmapPattern5x7(ch)
    % Patterns are 7 rows high.  Width is 3 or 5 pixels depending on glyph.
    switch ch
        case '0'
            rows = {'111','101','101','101','101','101','111'};
        case '1'
            rows = {'010','110','010','010','010','010','111'};
        case '2'
            rows = {'111','001','001','111','100','100','111'};
        case '3'
            rows = {'111','001','001','111','001','001','111'};
        case '4'
            rows = {'101','101','101','111','001','001','001'};
        case '5'
            rows = {'111','100','100','111','001','001','111'};
        case '6'
            rows = {'111','100','100','111','101','101','111'};
        case '7'
            rows = {'111','001','001','010','010','100','100'};
        case '8'
            rows = {'111','101','101','111','101','101','111'};
        case '9'
            rows = {'111','101','101','111','001','001','111'};
        case '.'
            rows = {'0','0','0','0','0','0','1'};
        case '-'
            rows = {'000','000','000','111','000','000','000'};
        case '|'
            rows = {'1','1','1','1','1','1','1'};
        case 'a'
            rows = {'000','000','111','001','111','101','111'};
        case 'd'
            rows = {'001','001','111','101','101','101','111'};
        case 'm'
            rows = {'00000','00000','11011','10101','10101','10101','10101'};
        case 'p'
            rows = {'000','000','111','101','111','100','100'};
        case 'r'
            rows = {'000','000','111','100','100','100','100'};
        otherwise
            pat = [];
            return;
    end
    pat = false(numel(rows), numel(rows{1}));
    for rr = 1:numel(rows)
        pat(rr,:) = rows{rr} == '1';
    end
end
